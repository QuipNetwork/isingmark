"""Planted-solution Ising problem generator.

Creates problems where a ground state is known by construction: each spin is
assigned a planted value, biases point toward that state, and a controllable
``frustration`` fraction of couplings are flipped to create energy barriers.
"""
from __future__ import annotations

import uuid
from typing import Any

from isingmark.chacha8 import ChaCha8Rng
from isingmark.models import IsingProblem
from isingmark.problems import register


class PlantedSolutionGenerator:
    """Generates Ising problems with a pre-planted ground state.

    Algorithm:
    1. Randomly assign ±1 spins to every node via ChaCha8Rng.
    2. Set h[node] = -planted_spin so that the planted state contributes
       negatively to the energy (biases toward it).
    3. For each edge (u, v):
       - The aligned coupling is J = -planted_spin[u] * planted_spin[v]
         (satisfied by the planted state).
       - With probability ``frustration``, flip the coupling to create a
         frustrated edge that the planted state does not satisfy.
    4. Store planted_spins in the problem metadata so callers can retrieve
       the known ground state.
    """

    @property
    def name(self) -> str:
        return "planted"

    def generate(
        self,
        seed: int,
        nodes: list[int],
        edges: list[tuple[int, int]],
        *,
        frustration: float = 0.1,
        **kwargs: Any,
    ) -> IsingProblem:
        """Generate a planted-solution Ising problem.

        Args:
            seed: u64 seed for ChaCha8Rng.
            nodes: List of node identifiers.
            edges: List of (u, v) edge tuples.
            frustration: Fraction of couplings to frustrate (flip).  Must be
                in [0, 1].  A value of 0 gives a ferromagnet with a known
                ground state; 0.5 is approximately random.
            **kwargs: Additional keyword arguments (ignored).

        Returns:
            IsingProblem with h, J populated and planted_spins in metadata.

        Raises:
            ValueError: If frustration is outside [0, 1].
        """
        if not (0.0 <= frustration <= 1.0):
            raise ValueError(f"frustration must be in [0, 1], got {frustration}")

        rng = ChaCha8Rng.seed_from_u64(seed)

        # Assign planted spins: even u32 → +1, odd u32 → -1
        planted_spins: dict[int, int] = {}
        for node in nodes:
            planted_spins[node] = 1 if (rng.next_u32() & 1) == 0 else -1

        # Biases toward the planted state
        h: dict[int, float] = {node: float(-planted_spins[node]) for node in nodes}

        # Couplings that prefer the planted state, with optional frustration
        J: dict[tuple[int, int], float] = {}
        frustration_threshold = int(frustration * (2**32))
        for u, v in edges:
            aligned_j = float(-planted_spins[u] * planted_spins[v])
            if rng.next_u32() < frustration_threshold:
                J[(u, v)] = -aligned_j  # frustrated coupling
            else:
                J[(u, v)] = aligned_j

        problem_id = str(uuid.uuid4())
        return IsingProblem(
            problem_id=problem_id,
            h=h,
            J=J,
            nodes=list(nodes),
            edges=[tuple(e) for e in edges],  # type: ignore[misc]
            problem_type=self.name,
            seed=seed,
            metadata={"planted_spins": planted_spins, "frustration": frustration},
        )

    def known_ground_energy(self, problem: IsingProblem) -> float | None:
        """Compute the energy of the planted spin configuration.

        Args:
            problem: An IsingProblem generated by this generator.

        Returns:
            The energy E = Σ h[i]*s[i] + Σ J[i,j]*s[i]*s[j] of the planted
            state, or None if planted_spins are missing from metadata.
        """
        planted: dict[int, int] | None = problem.metadata.get("planted_spins")
        if planted is None:
            return None

        energy = sum(problem.h[node] * planted[node] for node in problem.nodes)
        energy += sum(
            j_val * planted[u] * planted[v]
            for (u, v), j_val in problem.J.items()
        )
        return float(energy)


register(PlantedSolutionGenerator())
